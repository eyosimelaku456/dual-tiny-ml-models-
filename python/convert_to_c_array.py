"""
=============================================================================
convert_to_c_array.py - TFLite Model → C Header Array
=============================================================================
Author  : TinyML Battery SOH Pipeline
Purpose : Convert model_int8.tflite to a C byte array (model_data.h)
          for inclusion in ESP32 firmware.

          Equivalent to running:  xxd -i model_int8.tflite > model_data.h
          but implemented in Python for cross-platform compatibility.

Outputs:
    - esp32/model_data.h
=============================================================================
"""

import os
import struct

MODELS_DIR = r"../models"
ESP32_DIR  = r"../esp32"

INPUT_TFLITE = os.path.join(MODELS_DIR, "model_int8.tflite")
OUTPUT_HEADER = os.path.join(ESP32_DIR, "model_data.h")

os.makedirs(ESP32_DIR, exist_ok=True)


def tflite_to_c_array(tflite_path: str, output_path: str):
    """
    Read a .tflite binary file and produce a C header with:
        - An unsigned char array containing the model bytes
        - An unsigned int for the model length

    This output is compatible with TensorFlow Lite for Microcontrollers
    model loading: GetModel(g_model_data)
    """
    with open(tflite_path, "rb") as f:
        model_bytes = f.read()

    model_len = len(model_bytes)
    print(f"[INFO] Model: {tflite_path}")
    print(f"[INFO] Size : {model_len} bytes ({model_len/1024:.2f} KB)")

    # Format as C hex array (16 bytes per line, matching xxd -i output)
    hex_lines = []
    for i in range(0, model_len, 16):
        chunk = model_bytes[i:i+16]
        hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
        hex_lines.append(f"  {hex_str}")

    hex_array = ",\n".join(hex_lines)

    header_content = f"""// ============================================================
// model_data.h - Auto-generated by convert_to_c_array.py
// DO NOT EDIT MANUALLY
//
// TFLite INT8 quantized model for Battery SOH estimation
// Generated from: {os.path.basename(tflite_path)}
// Model size: {model_len} bytes ({model_len/1024:.2f} KB)
//
// Usage in firmware:
//   #include "model_data.h"
//   const tflite::Model* model = tflite::GetModel(g_model_data);
// ============================================================

#ifndef MODEL_DATA_H
#define MODEL_DATA_H

// Total size of model in bytes
#define MODEL_DATA_LEN {model_len}

// Model byte array (aligned for 4-byte access required by TFLM)
alignas(8) const unsigned char g_model_data[] = {{
{hex_array}
}};

const unsigned int g_model_data_len = {model_len};

#endif // MODEL_DATA_H
"""

    with open(output_path, "w") as f:
        f.write(header_content)

    print(f"[INFO] C header saved → {output_path}")
    print(f"[INFO] Array name: g_model_data (len: g_model_data_len)")


if __name__ == "__main__":
    print("=" * 60)
    print("  TFLite → C Array Converter")
    print("=" * 60)

    if not os.path.exists(INPUT_TFLITE):
        raise FileNotFoundError(
            f"model_int8.tflite not found at: {INPUT_TFLITE}\n"
            "Run convert_quantize.py first!"
        )

    tflite_to_c_array(INPUT_TFLITE, OUTPUT_HEADER)
    print(f"\n[✓] model_data.h ready for ESP32 firmware!")
    print(f"    Include in your firmware: #include \"model_data.h\"")
